"""Маршрутизация CRM-outbox событий в шарды Redis-очередей: шард задачи = id % N.

shard_for_id() вызывается РОВНО ОДИН РАЗ за жизнь агрегата (Task) — на первом
его outbox-событии (см. src/services/tasks.py::create_task) — результат
сохраняется в Task.crm_shard (sticky assignment) и больше не пересчитывается.
Повторный вызов на каждое событие был бы небезопасен: смена числа шардов между
двумя событиями одной задачи могла бы развести их по разным очередям, нарушив
строгий порядок обработки. Именно поэтому хеш-кольцо (consistent hashing) здесь
не нужно: его единственное преимущество — мало «переездов» уже размещённых
ключей при смене числа шардов — при sticky-присвоении не используется вовсе
(размещённые задачи не переезжают никогда), а недостатки остаются (сложнее код,
неровное распределение на малых выборках). id % N для последовательных
автоинкрементных id раздаёт задачи строго по кругу: 0, 1, 2, 3, 0, 1, ...

Ограничения формулы:
- Число шардов можно УВЕЛИЧИВАТЬ свободно: старые задачи остаются на своих
  шардах, новые распределяются по всем. Для нового шарда нужен сервис
  celery-worker-shard-N в src/docker-compose.yml.
- Число шардов НЕЛЬЗЯ уменьшать, пока в task.crm_shard есть значения удаляемых
  шардов: их очереди останутся без воркера, события зависнут в pending.
- Равномерность — по числу задач, не по «весу»: подзадачи наследуют шард
  родителя, поэтому задача с многими подзадачами нагружает свой шард сильнее.
"""

from src.crm.crm_config import crm_settings


def shard_names(count: int | None = None) -> list[str]:
    """Имена шардов shard_0..shard_{count-1} — очередь Celery продюсер строит
    как f"crm_sync.{shard}". count=None читает актуальное
    crm_settings.OUTBOX_SHARD_COUNT — не кэшируется на уровне модуля, чтобы
    тесты могли переопределять число шардов без reload.
    """
    n = count if count is not None else crm_settings.OUTBOX_SHARD_COUNT
    return [f"shard_{i}" for i in range(n)]


def shard_for_id(entity_id: int, count: int | None = None) -> str:
    """Шард для нового ключа: id % N. Чистая функция — сама ничего не запоминает."""
    names = shard_names(count)
    return names[entity_id % len(names)]


def ensure_task_shard(task) -> str:
    """Возвращает уже назначенный task.crm_shard (sticky assignment на первом
    outbox-событии задачи) или, для задач, созданных ДО внедрения
    шардирования (crm_shard всё ещё NULL), назначает его лениво прямо сейчас —
    без отдельной backfill-миграции (см. migration 0017).

    Общая точка для src/services/tasks.py, subtasks.py и attachments.py — у
    Subtask своего crm_shard нет: шард всегда берётся из родительской task,
    вызывающий код передаёт сюда именно её. Принимает любой объект с
    атрибутами id/crm_shard, чтобы не импортировать src.task_logic.models —
    этот модуль сознательно не знает о доменных моделях.
    """
    if task.crm_shard is None:
        task.crm_shard = shard_for_id(task.id)
    return task.crm_shard
