"""Token-bucket ограничитель скорости запросов к CRM — нужен на
случай разбора большого backlog после простоя CRM: reconcile_pending_outbox
может разом вернуть в очередь сотни накопившихся pending-строк, и без
ограничителя несколько шардов одновременно «выстрелили» бы пачкой запросов
в единственный demo-инстанс CRM.

Реализация — фиксированное окно (не классический token-bucket с постоянным
пополнением, но с той же целью: не больше N запросов в секунду), INCR+EXPIRE
на один общий ключ crm_rate_limit — все шарды делят один и тот же лимит,
поскольку ограничение накладывает сам demo-CRM-инстанс, а не отдельный шард.
"""

import redis.asyncio as redis

from src.config import settings
from src.crm.crm_config import crm_settings


async def acquire_slot() -> bool:
    """True — можно выполнять запрос к CRM прямо сейчас; False — лимит на
    текущую секунду исчерпан, вызывающий код должен отложить попытку
    (в Celery-задаче — retry с небольшим countdown, не немедленный повтор).

    INCR создаёт ключ при первом обращении в окне и возвращает 1.
    `EXPIRE ... NX` ставит TTL, только если у ключа его ЕЩЁ НЕТ — не просто
    оптимизация «ставить один раз при count==1» (так было раньше), а
    самовосстановление: если предыдущий вызов успел выполнить INCR, но упал
    ДО EXPIRE (сеть, падение процесса, в т.ч. класс ошибок "Event loop is
    closed" из-за переиспользования соединения между asyncio.run() — см. ниже
    про изоляцию клиента), ключ остаётся БЕССРОЧНЫМ и без NX-варианта
    навсегда блокировал бы все последующие CRM-вызовы — обнаружено живым
    прогоном docker compose up: TTL ключа оказался -1 (нет TTL) после серии
    крашей в старой версии этой функции, ограничитель перестал открываться
    вообще. `NX` (не безусловный повторный EXPIRE на каждый вызов) сохраняет
    исходную защиту от "sliding window": уже установленный TTL не сдвигается
    вперёд при высокой частоте вызовов, окно остаётся привязанным к моменту
    первого INCR.

    Клиент создаётся и закрывается В ПРЕДЕЛАХ ЭТОГО ЖЕ вызова, а не хранится
    как module-level singleton между вызовами (в отличие, например, от
    src/crm/client.py::_get_shared_http_client) — эта функция вызывается
    из Celery-задач, каждая из которых выполняется через
    src.celery_app.run_celery_task() в СВОЁМ собственном asyncio.run().
    Соединение redis-py, открытое в одном event loop, при попытке
    переиспользовать его в следующем asyncio.run() (новый loop) падает
    "RuntimeError: Event loop is closed" при закрытии — обнаружено живым
    прогоном docker compose up (юнит-тесты не ловят: не выполняют два
    реальных asyncio.run() подряд в одном процессе поверх одного клиента).
    Тот же класс проблемы, что и с SQLAlchemy engine — см. докстринг
    run_celery_task().
    """
    client = redis.from_url(settings.REDIS_URL)
    try:
        count = await client.incr("crm_rate_limit")
        await client.expire("crm_rate_limit", 1, nx=True)
        return count <= crm_settings.RATE_LIMIT_PER_SECOND
    finally:
        await client.aclose()
